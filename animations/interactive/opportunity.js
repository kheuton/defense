// ── Phase controller ──────────────────────────────────────────────────────────

const PHASES = 4;
let currentPhase = -1;
let transitioning = false;

function applyPhase(n) {
  switch (n) {
    case 0:
      break;
    case 1:
      bigCookGroup.querySelectorAll('[data-method="spo"], [data-method="pg"]').forEach(e => {
        e.style.opacity = '1';
      });
      break;
    case 2:
      bigCookArrow.style.opacity = '1';
      break;
    case 3:
      bigCookGroup.style.opacity = '0';
      smallGroup.style.opacity = '1';
      break;
    case 4:
      textGroup.style.opacity = '1';
      break;
  }
}

function advancePhase() {
  if (transitioning) return;
  currentPhase++;
  if (currentPhase > PHASES) return;
  transitioning = true;
  applyPhase(currentPhase);
  setTimeout(() => { transitioning = false; }, 450);
  if (currentPhase >= PHASES) removeListeners();
}

function onClick() { advancePhase(); }
function onKeyDown(e) { if (e.key === 'ArrowRight' || e.key === ' ') advancePhase(); }
function removeListeners() {
  const svg = document.getElementById('viz');
  svg.removeEventListener('click', onClick);
  document.removeEventListener('keydown', onKeyDown);
  const hud = document.getElementById('hud');
  if (hud) hud.classList.add('hidden');
}

// ── Init ──────────────────────────────────────────────────────────────────────

function init() {
  const svg = document.getElementById('viz');
  buildBigCook(svg);
  buildSmallLayout(svg);
  buildTextPanel(svg);

  svg.addEventListener('click', onClick);
  document.addEventListener('keydown', onKeyDown);
  try {
    const _R = window.parent.Reveal;
    const myFile = window.location.pathname.split('/').pop();
    _R.on('fragmentshown', () => {
      const bgIframe = _R.getCurrentSlide()?.dataset?.backgroundIframe ?? '';
      if (bgIframe.includes(myFile)) advancePhase();
    });
  } catch (_) {}
}

document.addEventListener('DOMContentLoaded', init);
